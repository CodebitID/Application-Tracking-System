export const parseSalaryToNumeric = (salaryStr: string | undefined): number | undefined => {
  if (!salaryStr || salaryStr.trim().toUpperCase() === 'N/A' || salaryStr.trim() === '') {
    return undefined;
  }
  const clean = salaryStr.replace(/[^0-9.]/g, '');
  const num = parseFloat(clean);
  return isNaN(num) ? undefined : num;
};

